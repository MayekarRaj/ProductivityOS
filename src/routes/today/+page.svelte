                    stroke-linecap="round" stroke-linejoin="round"/>
            </svg>
          {/if}
        </button>
        <div>
          <p class="font-mono text-[9px] font-semibold uppercase tracking-[0.12em] text-amber-500/70">
            MVD Goal
