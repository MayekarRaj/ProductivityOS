              Went to bed
            </label>
            <input
              id="bedTime"
              type="time"
              name="bedTime"
              bind:value={bedTime}
              onblur={(e) => e.currentTarget.form?.requestSubmit()}
              class="w-full rounded border border-[#1e1e2e] bg-[#0c0c0f] px-2 py-1.5
