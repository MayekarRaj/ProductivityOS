<script lang="ts">
	// SvelteKit provides `enhance` — a Svelte action that intercepts form submissions
	// and uses fetch instead of a full page reload. After the server action runs,
	// it automatically re-runs the load() function so `data` stays fresh.
	import { enhance } from '$app/forms';
	// untrack() tells Svelte "read this reactive value once without subscribing to changes"
	// Used below to initialize local state from props without triggering the
	// "state_referenced_locally" warning — our intent is exactly a one-time snapshot.
	import { untrack } from 'svelte';

	// PageData is auto-generated by `svelte-kit sync` — it reflects the return
	// type of our load() function in +page.server.ts. Fully type-safe.
	import type { PageData } from './$types';

	import { areaFor, colorClasses } from '$lib/constants/areas';
	import { MVD_HINTS, ENERGY_LEVELS } from '$lib/constants/defaults';
	import { formatDateLong, formatTimeIST, getGreetingIST } from '$lib/utils/dates';
	import PanelCard from '$lib/components/PanelCard.svelte';
	import PomodoroTimer from '$lib/components/PomodoroTimer.svelte';
	import TwoColumnPage from '$lib/components/TwoColumnPage.svelte';

	// Svelte 5: `$props()` replaces `export let data`.
	// The type annotation ensures `data` matches what our load() function returns.
	let { data }: { data: PageData } = $props();

	// ── Local UI state ────────────────────────────────────────────────────────
	// These are ephemeral input values — not persisted until a form is submitted.
	// $state() is Svelte 5's reactive primitive (replaces `let` with two-way binding).
	let newTaskText = $state('');
	let newTaskArea = $state(untrack(() => data.day.homeBase));
	let newInboxText = $state('');
	let showAddEvent = $state(false);
	let newEventTitle = $state('');
	let newEventTime = $state('');
	let newEventEndTime = $state('');
	let newEventArea = $state(untrack(() => data.day.homeBase));
	let newEventRemindOffset = $state('5'); // minutes before start

	// ── Recurring events UI state ─────────────────────────────────────────────
	let showManageRecurring = $state(false);
	let showAddRecurring = $state(false);
	const WEEKDAYS = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
	let newRecurringDays = $state<string[]>([]);

	// ── Sleep state ───────────────────────────────────────────────────────────
	// Pre-populated from DB if sleep was logged previously (converts UTC → IST HH:MM)
	let bedTime = $state(data.day.sleepStart ? formatTimeIST(data.day.sleepStart) : '');
	let wakeTime = $state(data.day.sleepEnd ? formatTimeIST(data.day.sleepEnd) : '');

	// Derived sleep duration for display (bed is "yesterday", wake is "today")
	const sleepDuration = $derived(() => {
		if (!bedTime || !wakeTime) return null;
		const [bedH, bedM] = bedTime.split(':').map(Number);
		const [wakeH, wakeM] = wakeTime.split(':').map(Number);
		const bedMins = bedH * 60 + bedM;
		const wakeMins = wakeH * 60 + wakeM;
		// Sleep crosses midnight, so add 24h worth of minutes to wake
		const durationMins = (wakeMins + 24 * 60 - bedMins) % (24 * 60);
		return { hours: Math.floor(durationMins / 60), mins: durationMins % 60 };
	});

	// ── AI state (9.1, 9.5) ───────────────────────────────────────────────────
	let nlInput = $state('');
	let nlResult = $state('');
	let briefing = $state<{ briefing: string; suggestions: string[] } | null>(null);
	let briefingLoading = $state(false);

	// ── New state for briefing collapse and live clock ─────────────────────────
	let briefingCollapsed = $state(false);
	let now = $state(new Date());

	// Live clock — updates every 30 seconds for ACTIVE event detection
	// $effect runs after mount and cleans up on destroy
	$effect(() => {
		const interval = setInterval(() => {
			now = new Date();
		}, 30_000);
		return () => clearInterval(interval);
	});

	// ── Briefing text renderer — parses [hl]...[/hl] and [area:key]...[/area] markers ──
	// Returns HTML string safe to use with {@html ...}
	function renderBriefing(text: string, areas: typeof data.areas): string {
		// Replace [area:key]...[/area] with area-colored spans
		let result = text.replace(/\[area:([^\]]+)\](.*?)\[\/area\]/g, (_, key, content) => {
			const area = areas.find(a => a.key === key);
			if (!area) return content;
			// Map color key to a Tailwind inline hex — using a simple lookup
			const colorMap: Record<string, string> = {
				blue: '#60a5fa', purple: '#c084fc', green: '#4ade80',
				orange: '#fb923c', rose: '#fb7185', amber: '#fbbf24',
				teal: '#2dd4bf', pink: '#f472b6', red: '#f87171', indigo: '#818cf8'
			};
			const hex = colorMap[area.color] ?? '#c084fc';
			return `<span style="color:${hex}">${content}</span>`;
		});

		// Replace [hl]...[/hl] with accent-colored spans
		result = result.replace(/\[hl\](.*?)\[\/hl\]/g,
			'<span class="text-violet-400 font-medium">$1</span>'
		);

		return result;
	}

	// ── Derived values ────────────────────────────────────────────────────────
	// $derived() is Svelte 5's computed value (replaces $: reactive declarations).
	// Re-evaluates automatically when its dependencies change.
	const homeArea = $derived(areaFor(data.day.homeBase, data.areas));
	const homeAreaColors = $derived(homeArea ? colorClasses(homeArea.color) : null);
	const mvdHint = $derived(MVD_HINTS[data.day.homeBase] ?? 'Do one meaningful thing');
	const greeting = $derived(getGreetingIST());
	const dateLabel = $derived(formatDateLong(data.day.date));

	// Split tasks into pending (top) and completed (bottom, collapsible)
	const pendingTasks = $derived(data.tasks.filter((t) => !t.done));
	const doneTasks = $derived(data.tasks.filter((t) => t.done));

	async function fetchBriefing() {
		briefingLoading = true;
		briefing = null;
		try {
			const res = await fetch('/api/ai/briefing');
			briefing = await res.json();
		} catch {
			briefing = { briefing: 'Could not load briefing. Check your connection.', suggestions: [] };
		}
		briefingLoading = false;
	}
</script>

